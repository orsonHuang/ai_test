const assert=require('node:assert/strict');
const E=require('../dist/engine.js');
assert.equal(E.initialIdeas().length,6);
assert(E.initialIdeas().every(x=>x.demo&&x.evidence.every(e=>e.demo)));
assert.equal(E.generateIdeas([]).ideas.length,0);
const source=E.validateSource({title:'测试观察',content:'玩家希望中断后重新打开时，可以记住之前的线索。',url:'https://example.com/research'});
const result=E.generateIdeas([source],{platform:'网页游戏',team:'1–2 人',budget:'1 周',topic:'旧书店'});
assert.equal(result.ideas.length,3);
assert(result.ideas.every(x=>!x.demo&&x.evidence.every(e=>e.sourceId===source.id)));
assert(result.ideas.every(x=>x.pitch.includes('旧书店')&&x.brief.platform==='网页游戏'));
assert.equal(E.generateIdeas([E.validateSource({title:'无法判断',content:'这是一段没有涉及预设主题的文字。'})]).ideas.length,0);
const manual=E.validateSource({title:'指定主题',content:'这是一段没有涉及预设主题的文字。',topic:'cozy'});
assert.equal(E.generateIdeas([manual],{method:'demand'}).ideas.length,1);
assert.equal(E.generateIdeas([manual],{method:'all'}).ideas.length,3);
assert.throws(()=>E.validateSource({title:'坏链接',content:'足够长度的测试资料内容。',url:'javascript:alert(1)'}),/链接/);
assert.equal(E.safeURL('data:text/html,hello'),'');
assert.throws(()=>E.parseBackup('{}'),/备份/);
const backup={version:1,sources:[source],ideas:result.ideas,brief:E.DEFAULT_BRIEF};
const parsed=E.parseBackup(JSON.stringify(backup));
assert.equal(parsed.ideas.length,3);assert.equal(parsed.sources[0].url,source.url);
assert.throws(()=>E.parseBackup({...backup,sources:[source,source]}),/重复/);
const exported=E.markdown(parsed.ideas[0]);
assert(exported.includes(source.url)&&exported.includes('未经独立核实')&&exported.includes('旧书店'));
assert(E.markdown(E.initialIdeas()[0]).includes('资料为虚构示例'));
console.log('Engine checks passed: provenance, nonmatch, manual topics, unique candidates, backup schema, links, exports.');
